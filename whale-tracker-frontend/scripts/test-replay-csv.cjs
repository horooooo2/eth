const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const context = vm.createContext({ exports: {} });
const source = fs.readFileSync(path.join(__dirname, '../src/tradfi-replay/csv.ts'), 'utf8');
vm.runInContext(ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText, context);
const { parseCandles, parseFunding, embeddedFunding } = context.exports;
const header = 'timestamp,open,high,low,close,volume,funding_rate,mark_price\n';
const data = header + '1736121600000,100,101,99,100,10,.0001,99.9\n1736121660000,100,101,99,100,10,0,100\n1736121720000,100,101,99,100,10,,100';
assert.equal(parseCandles(data, 60000, 3).length, 3);
const fund = embeddedFunding(data);
assert.equal(fund.length, 1, 'Zero placeholders are not settlement events');
assert.equal(fund[0].price, 99.9);
assert.equal(fund[0].rate, .0001);
assert.equal(embeddedFunding('timestamp,open\n1736121600000,100'), null);
assert.throws(() => parseFunding('timestamp,fundingRate\n1736121600000,'), /缺少/);
assert.throws(() => parseFunding('timestamp,fundingRate\n1736121600000,.1\n1736121600000,.2'), /重复/);
assert.throws(() => parseFunding('timestamp,fundingRate,mark_price\n1736121600000,.1,-100'), /参考价/);
assert.throws(() => parseCandles(data.replace('1736121660000', '1736121600000'), 60000, 3), /重复/);
assert.throws(() => parseCandles(data.replace('1736121660000', '1736121660001'), 60000, 3), /边界/);
assert.throws(() => parseCandles(data.replace('1736121720000', '1736121780000'), 60000, 3), /缺失/);
assert.throws(() => parseCandles(data.replace('mark_price', 'volume'), 60000, 3), /列名/);
console.log('Shared CSV: candles, embedded funding, mark prices, missing/duplicate timestamps and malformed data passed');
