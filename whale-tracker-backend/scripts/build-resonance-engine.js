// Generate the server scanner from the existing, tested UI algorithm and helpers.
// No TypeScript or browser dependencies are needed on the production server.
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '../../whale-tracker-frontend');
const ts = require(path.join(root, 'node_modules/typescript'));
function source(file) { return fs.readFileSync(path.join(root, 'src/utils', file), 'utf8'); }
function functions(file, names) {
  const code = source(file);
  const ast = ts.createSourceFile(file, code, ts.ScriptTarget.Latest, true);
  return ast.statements.filter(node => ts.isFunctionDeclaration(node) && names.includes(node.name?.text))
    .map(node => node.getText(ast).replace(/^export /, '')).join('\n');
}
const helpers = [
  'const WAN = 10000, YI = 100000000, MAINTENANCE_MARGIN_RATE = 0.004;',
  functions('format.ts', ['formatUsd', 'formatWanNumber', 'formatYiNumber', 'trimTrailingZeros']),
  functions('liquidationEstimate.ts', ['estimateLiquidationPx']),
  functions('whaleAlerts.ts', ['alertEventTime', 'inferSide', 'tradeFillSide']),
  functions('watchedCoins.ts', ['normalizeCoinId', 'coinMatchesWatch']),
  'function readWatchedCoins() { return []; }',
].join('\n');
const scanner = source('whaleResonanceSignal.ts').replace(/^import .*\r?\n/gm, '');
const output = ts.transpileModule(`${helpers}\n${scanner}`, {
  compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS },
}).outputText;
const generated = '// Generated by scripts/build-resonance-engine.js. Edit the source utilities, then regenerate.\n' + output;
const target = path.resolve(__dirname, '../lib/resonanceEngine.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== generated) throw new Error('Resonance engine is out of date');
} else fs.writeFileSync(target, generated);
